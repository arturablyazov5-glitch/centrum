// Панели для наушников — docs/headphones. Концепция 26.09.2026.
//
// В кармане снизу внутренней кромки стоит вставка из анодированного алюминия,
// в её задней стенке — гнёзда заподлицо: USB-A, 3,5 мм (4 контакта, CTIA), USB-C.
// Панели пассивные: гнёзда и провод до распределителя в Tech Bay, он подключён
// к разъёмам передней панели на плате ПК. Кромка — ближайшее к голове место стола:
// до уха около 0,7 м, кабеля 1,2 м хватает.
//
// Центральная панель (под клавиатурой) — в базе. Левая и правая, у бёдер, — опция:
// карманы и канал под кабель есть в каждом столе, без опции в них стоит глухая
// вставка того же вида, и панель ставится потом за один визит.
//
// Штекер смотрит горизонтально на человека: кабель уходит к уху под ~50° к оси
// штекера, у вставшего — под ~70° (схема 04 в docs/headphones). Колодцев вокруг
// гнёзд нет — корпуса штекеров слишком разные.
//
// Координаты — как у корпуса до отражения (mirror.js); θ — от оси экрана, плюс —
// вправо от сидящего.

import { R_HOLE, UNDER_1 } from './params.js';

export const AUDIO_POCKET = Object.freeze({
  length: 111,            // чистый проём; с кромками прежние 116 мм по дуге R_FACE
  depth: 20,              // от кромки отверстия R500 до лица панели
  height: 38,             // от низа столешницы +760 до потолка кармана +798
  back: 8,                // панель с гнёздами
  mouth: 2.5,             // внутреннее скругление чёрной вставки
  overlap: 2.5,           // нахлёст металлического канта на дерево
  lipProjection: 1.2,     // выступ канта перед лицом дерева
  lipRound: 0.6,          // скругление наружного края канта
  faceRound: 1.5,         // скругление нижней кромки панели
  gap: 0.6,               // теневой зазор между панелью и откосами
});

export const R_FACE = R_HOLE + AUDIO_POCKET.depth;                 // 520 — лицо панели
export const R_BACK = R_FACE + AUDIO_POCKET.back;                  // 528 — задняя грань вставки
export const Z_CEIL = UNDER_1 + AUDIO_POCKET.height;               // 798 — потолок кармана
export const Z_CUT = Z_CEIL + AUDIO_POCKET.mouth;                  // верх прямого выреза в дереве
export const Z_PORT = (UNDER_1 + Z_CEIL) / 2;                      // 779 — ось гнёзд

// Дерево имеет прямой вырез без выступающей губы. Чёрная вставка закрывает
// откосы и перекрывает вырез кантом; входной радиус и мягкий наружный край — металл.
// Панель с гнёздами остаётся в глубине, её нижняя кромка — R1,5.

// Центр — в базе, бока — опция «Боковые панели для наушников».
export const AUDIO_PANELS = Object.freeze([
  { id: 'center', theta: 0, base: true },
  { id: 'left', theta: -80, base: false },
  { id: 'right', theta: 80, base: false },
]);

// Гнёзда по дуге от середины панели, плюс — вправо для смотрящего на панель.
// Вырез в стенке — по наружному контуру корпуса гнезда.
export const AUDIO_PORTS = Object.freeze([
  { id: 'usbA', s: -26, hole: [12.6, 5.22, 0.45] },
  { id: 'jack', s: 0, hole: [6.5, 6.5, 3.25] },
  { id: 'usbC', s: 26, hole: [9.0, 3.32, 1.66] },
]);

// Откидной крючок для наушников — в базе, слева за левой панелью, в потолке ниши.
export const AUDIO_HOOK = Object.freeze({ theta: -92.5, r: [598, 655], width: 22, drop: 62 });

// Половина углового размера кармана со скруглением устья, градусы.
const D = Math.PI / 180;
export const pocketHalf = () => (AUDIO_POCKET.length / 2 + AUDIO_POCKET.mouth) / R_FACE / D;
export const arcDeg = (s) => s / R_FACE / D;
