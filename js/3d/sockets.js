// Блок из трёх розеток на внутренней стенке пояса R1150 между уровнями.
// Одно описание на всё: где стоят рамки (load-monitor.js) и где в стенке
// вырезаны отверстия под их гнёзда (build-core.js).
//
// Стенка — цилиндр, поэтому каждая рамка стоит по своей касательной: угол
// соседних рамок отличается на 2·atan(42,5 / 1150) ≈ 4,2°. Задние кромки рамок
// 84 мм при этом сходятся с зазором 1 мм, а не уходят в стенку.
// Середина блока — справа от сидящего (угол 200°), рядом с телефоном и кружкой,
// не за монитором. Центр рамок на 130 мм выше рабочей поверхности.

import { LEVEL_1, R_BELT_HIGH } from './params.js';

export const SOCKET_FRAME = 84;       // рамка, мм
export const SOCKET_HOLE = 64;        // квадратное отверстие в стенке под гнездо, мм
export const SOCKET_Z = LEVEL_1 + 130;
const STEP = 2 * Math.atan((SOCKET_FRAME / 2 + 0.5) / R_BELT_HIGH);
const MIDDLE = 200 * Math.PI / 180;

// Углы рамок в мировой системе сцены (после отражения корпуса, см. mirror.js).
export const SOCKET_ANGLES = [MIDDLE - STEP, MIDDLE, MIDDLE + STEP];
